#!/usr/bin/env python3
"""Generate three short concept figures, leaving older attached originals intact.

Each figure answers one question: direction, process containment, or CDC path.
Only the Python standard library is required. Output is published via Issue assets.
"""
import argparse
from html import escape
from pathlib import Path
import tempfile
import xml.etree.ElementTree as ET

from kafka_integration_diagrams import BG, INK, LINE, WHITE, FONT

ROOT = Path(__file__).resolve().parents[2]


class ConceptFigure:
    def __init__(self, name, height, title, description, width=760):
        self.name, self.width, self.height = name, width, height
        self.prefix = Path(name).stem
        self.title, self.description = title, description
        self.frames, self.edges, self.nodes, self.labels = [], [], [], []

    def text(self, x, y, text, size=34, bold=False, anchor='middle'):
        self.labels.append(
            f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" '
            f'font-weight="{600 if bold else 400}" text-anchor="{anchor}" '
            f'fill="{INK}">{escape(text)}</text>')

    def box(self, x, y, w, h, frame=False, focus=False):
        layer = self.frames if frame else self.nodes
        fill = BG if frame else ('#e8edf4' if focus else WHITE)
        layer.append(
            f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="12" '
            f'fill="{fill}" stroke="{LINE}" stroke-width="{4 if focus else 3}"/>')

    def database(self, x, y, w, h):
        self.nodes.append(
            f'<path d="M {x} {y+16} V {y+h-16} '
            f'C {x} {y+h+6} {x+w} {y+h+6} {x+w} {y+h-16} V {y+16}" '
            f'fill="{WHITE}" stroke="{LINE}" stroke-width="3"/>')
        self.nodes.append(
            f'<ellipse cx="{x+w/2}" cy="{y+16}" rx="{w/2}" ry="16" '
            f'fill="{WHITE}" stroke="{LINE}" stroke-width="3"/>')

    def arrow(self, x1, x2, y, dashed=False):
        dash = ' stroke-dasharray="10 8"' if dashed else ''
        self.edges.append(
            f'<path d="M {x1} {y} H {x2}" fill="none" stroke="{LINE}" '
            f'stroke-width="3"{dash} marker-end="url(#{self.prefix}-arrow)"/>')

    def save(self, output):
        p = self.prefix
        header = [
            '<?xml version="1.0" encoding="UTF-8"?>',
            '<!-- Generated by scripts/generation/kafka_concept_diagrams.py -->',
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.width}" '
            f'height="{self.height}" viewBox="0 0 {self.width} {self.height}" '
            f'role="img" aria-labelledby="{p}-title {p}-desc">',
            f'<title id="{p}-title">{escape(self.title)}</title>',
            f'<desc id="{p}-desc">{escape(self.description)}</desc>',
            f'<defs><marker id="{p}-arrow" markerWidth="16" markerHeight="12" '
            f'refX="15" refY="6" orient="auto" markerUnits="userSpaceOnUse">'
            f'<path d="M 0 0 L 16 6 L 0 12 Z" fill="{LINE}"/></marker></defs>',
            f'<rect width="{self.width}" height="{self.height}" fill="{BG}"/>',
        ]
        svg = '\n'.join(header + self.frames + self.edges + self.nodes + self.labels + ['</svg>', ''])
        ET.fromstring(svg)
        path = output / self.name
        path.write_text(svg, encoding='utf-8')
        print(path)


def source_sink(output):
    f = ConceptFigure(
        'fig-14-source-sink.svg', 224, 'Kafka를 기준으로 한 Source와 Sink의 방향',
        '주문 DB에서 Kafka로 향하는 화살표는 Source, Kafka에서 검색 엔진으로 '
        '향하는 화살표는 Sink다. 두 화살표는 데이터 이동이며 직접 호출 관계가 아니다.')
    f.arrow(180, 296, 136)
    f.arrow(464, 580, 136)
    f.database(16, 80, 164, 104)
    f.box(296, 80, 168, 104, focus=True)
    f.box(580, 80, 164, 104)
    f.text(98, 148, '주문 DB', bold=True)
    f.text(380, 148, 'Kafka', 36, True)
    f.text(662, 148, '검색 엔진', bold=True)
    f.text(238, 112, 'Source', bold=True)
    f.text(522, 112, 'Sink', bold=True)
    f.save(output)


