def wal_path(output):
    f = ConceptFigure(
        'fig-15-wal-debezium-path.svg', 272, 'WAL의 변경 정보가 Kafka로 전달되는 경로',
        '초기 snapshot 이후의 PostgreSQL streaming 경로다. PostgreSQL 안의 WAL에서 '
        'logical decoding으로 얻은 행 변경 스트림을 Connect Worker 안의 Debezium '
        'source task가 받는다. Worker가 레코드를 Kafka에 발행한다. WAL 파일 자체를 '
        'Task에 넘기는 그림이나 데이터 파일 반영과 Kafka 발행의 완료 순서를 뜻하지 않는다.',
        width=784)
    f.box(16, 16, 208, 240, frame=True)
    f.box(344, 16, 224, 240, frame=True)
    f.arrow(200, 368, 168)
    f.arrow(544, 664, 168)
    f.box(40, 112, 160, 112)
    f.box(368, 112, 176, 112, focus=True)
    f.box(664, 112, 104, 112)
    f.text(120, 64, 'PostgreSQL', bold=True)
    f.text(456, 64, 'Worker', 36, True)
    f.text(120, 152, 'WAL', 40, True)
    f.text(120, 204, '변경 로그')
    f.text(456, 152, 'Debezium', bold=True)
    f.text(456, 204, 'Source task')
    f.text(716, 180, 'Kafka', bold=True)
    f.text(284, 140, '행 변경')
    f.text(616, 140, '발행')
